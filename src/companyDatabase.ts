export function searchCompany(query: string): CompanyEntry[] {
  if (!query || query.length < 2) return [];
  const q = query.toLowerCase().replace(/[\s　株式会社]/g, '');

  // ローカルDB + カスタム + AIキャッシュを統合検索
  const allCompanies = [...companyDatabase, ...getCustomCompanies()];

  // AIキャッシュからもエントリを生成
  const aiCache = getAIClassificationCache();
  const aiEntries: CompanyEntry[] = Object.entries(aiCache).map(([name, result]) => ({
    name,
    type: result.type,
    alias: [],
    sub: `AI判定: ${result.sub || ''}（${Math.round(result.confidence * 100)}%）`,
  }));

  const combined = [...allCompanies, ...aiEntries];

  // 重複排除（同じ名前はローカルDBを優先）
  const seen = new Set<string>();
  const unique = combined.filter(c => {
    if (seen.has(c.name)) return false;
    seen.add(c.name);
    return true;
  });

  return unique.filter(c => {
    const nameNorm = c.name.toLowerCase().replace(/[\s　株式会社]/g, '');
    const nameMatch = nameNorm.includes(q);
    const aliasMatch = c.alias ? c.alias.some(a => a.toLowerCase().replace(/[\s　株式会社]/g, '').includes(q)) : false;
    return nameMatch || aliasMatch;
  }).slice(0, 10);
}

